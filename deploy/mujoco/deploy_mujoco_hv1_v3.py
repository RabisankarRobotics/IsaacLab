"""
Deploy a trained HV1 V3 (HiWET Stage-1) loco-manip policy in MuJoCo.

V3 differs from V2 in four ways the deploy runner must handle:

  1. Two extra scalar command obs: body_height_command, waist_alpha_command.
  2. Torso IMU obs (projected_gravity_torso, torso_ang_vel) — V2 deploy script
     omitted these; V3 policy was trained with them so they must be supplied.
  3. Observation history (length 5) — actor input is 605-d, not 121-d. Each
     obs term is buffered separately (CircularBuffer in Isaac), then per-term
     histories are flattened oldest→newest and concatenated in declaration
     order. This script mirrors that exactly.
  4. Action dim 28 (legs 12 + arms 14 + waist 2). Joint order from YAML.

The YAML is generated by:
  ./isaaclab.sh -p scripts/reinforcement_learning/rsl_rl/dump_mujoco_config.py \\
      --task Isaac-Tracking-LocoManipV3-HV1-Play-v0 --num_envs 1

Usage:
  python deploy_mujoco_hv1_v3.py \\
      --config <run_dir>/exported/mujoco_config.yaml \\
      --cmd_lin_x 0.3 --cmd_lin_y 0.0 --cmd_ang_z 0.0 \\
      --left_ee   0.30  0.26 0.24  1.0 0.0 0.0 0.0 \\
      --right_ee  0.30 -0.26 0.24  1.0 0.0 0.0 0.0 \\
      --cmd_body_height 0.90 \\
      --cmd_waist_alpha 1.0
"""

from __future__ import annotations

import argparse
import sys
import time
from collections import deque
from typing import Callable, Dict, List, Tuple

import mujoco
import mujoco.viewer
import numpy as np
import torch
import yaml


# ---------------------------------------------------------------------------
# Math — matches Isaac Lab quaternion convention (w, x, y, z)
# ---------------------------------------------------------------------------

def quat_rotate_inverse(q: np.ndarray, v: np.ndarray) -> np.ndarray:
    """Rotate world-frame vector v into body frame using body-to-world quat q."""
    qw = q[0]
    qvec = q[1:4]
    a = v * (2.0 * qw * qw - 1.0)
    b = np.cross(qvec, v) * (2.0 * qw)
    c = qvec * (2.0 * np.dot(qvec, v))
    return a - b + c


def projected_gravity_in_frame(quat: np.ndarray) -> np.ndarray:
    """Gravity unit vector rotated into the frame defined by `quat`."""
    return quat_rotate_inverse(quat, np.array([0.0, 0.0, -1.0], dtype=np.float32))


# ---------------------------------------------------------------------------
# MuJoCo helpers

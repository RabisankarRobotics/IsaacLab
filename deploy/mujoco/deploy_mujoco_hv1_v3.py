# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Deploy HV1 V3 loco-manip policy in MuJoCo.")
    parser.add_argument("--config", type=str, required=True, help="Path to mujoco_config.yaml (V3).")
    parser.add_argument("--policy", type=str, default=None, help="Override policy.pt path.")
    parser.add_argument("--xml", type=str, default=None, help="Override MJCF path.")
    parser.add_argument("--duration", type=float, default=120.0)
    parser.add_argument("--base_height", type=float, default=None)
    parser.add_argument("--realtime", action="store_true", default=True)
    # base velocity command
    parser.add_argument("--cmd_lin_x", type=float, default=0.0)
    parser.add_argument("--cmd_lin_y", type=float, default=0.0)
    parser.add_argument("--cmd_ang_z", type=float, default=0.0)
    # EE pose commands (pelvis frame)
    parser.add_argument(
        "--left_ee", nargs=7, type=float,
        default=[0.30, 0.26, 0.24, 1.0, 0.0, 0.0, 0.0],
        help="Left EE: px py pz qw qx qy qz (pelvis frame)",
    )
    parser.add_argument(
        "--right_ee", nargs=7, type=float,
        default=[0.30, -0.26, 0.24, 1.0, 0.0, 0.0, 0.0],
        help="Right EE: px py pz qw qx qy qz (pelvis frame)",
    )
    # V3-only scalar commands
    parser.add_argument(
        "--cmd_body_height", type=float, default=0.90,
        help="Target body (pelvis) height in metres. Training range [0.85, 0.95].",
    )
    parser.add_argument(
        "--cmd_waist_alpha", type=float, default=1.0,
        help="Waist regularization alpha_t. Training range [0.1, 3.0]; "
             "1.0 ≈ nominal waist stiffness.",
    )
    # Obs structure overrides (only needed if YAML doesn't match defaults)
    parser.add_argument(
        "--history_length", type=int, default=5,
        help="History buffer length per obs term. Must match training value.",
    )
    args = parser.parse_args()

    # ---- Load config ------------------------------------------------------
    with open(args.config, "r") as f:
        cfg = yaml.safe_load(f)

    xml_path = args.xml or cfg["robot"]["xml_path"]
    policy_path = args.policy or cfg["policy"]["jit_path"]
    sim_dt = float(cfg["control"]["sim_dt"])
    decimation = int(cfg["control"]["decimation"])
    joint_names_isaac = cfg["robot"]["joint_names_isaac_order"]
    joint_names_action = cfg["action"]["joint_names_action_order"]
    q_default_isaac = np.array(cfg["robot"]["default_joint_pos"], dtype=np.float32)
    kp_isaac = np.array(cfg["robot"]["kp"], dtype=np.float32)
    kd_isaac = np.array(cfg["robot"]["kd"], dtype=np.float32)
    action_scale = float(cfg["action"]["scale"])
    use_default_offset = bool(cfg["action"]["use_default_offset"])
    n_dof = int(cfg["robot"]["num_dof_total"])
    action_dim = int(cfg["action"]["dim"])
    total_obs_dim_yaml = int(cfg["observation"]["total_dim"])
    obs_terms_yaml = cfg["observation"]["terms"]  # list of {name, dim}; dim is post-history-flatten

    # Build single-frame dim table by dividing YAML per-term dim by history_length.
    # (dump_mujoco_config reports flattened dim; we want single frame for buffer
    # bookkeeping.)
    history_length = args.history_length
    single_frame_dims: Dict[str, int] = {}
    obs_term_order: List[str] = []
    for entry in obs_terms_yaml:
        name = entry["name"]
        dim_total = int(entry["dim"])
        if dim_total % history_length != 0:
            raise RuntimeError(
                f"Term '{name}' YAML dim {dim_total} not divisible by history "
                f"length {history_length}. Was training history_length different?"
            )
        single_frame_dims[name] = dim_total // history_length
        obs_term_order.append(name)

    single_frame_total = sum(single_frame_dims.values())
    if single_frame_total * history_length != total_obs_dim_yaml:
        raise RuntimeError(
            f"YAML total obs {total_obs_dim_yaml} != sum(per-term × history) "
            f"{single_frame_total * history_length}. Obs structure mismatch."
        )

    print(f"[deploy] config            : {args.config}")
    print(f"[deploy] xml               : {xml_path}")
    print(f"[deploy] policy            : {policy_path}")
    print(f"[deploy] sim_dt            : {sim_dt}  decimation={decimation}  policy_dt={sim_dt * decimation}")
    print(f"[deploy] n_dof_total       : {n_dof}    action_dim={action_dim}")
    print(f"[deploy] action_scale      : {action_scale}    use_default_offset={use_default_offset}")
    print(f"[deploy] history_length    : {history_length}")
    print(f"[deploy] single_frame_dim  : {single_frame_total}")
    print(f"[deploy] total_obs_dim     : {total_obs_dim_yaml}  (from YAML)")
    print(f"[deploy] obs term order    :")
    for name in obs_term_order:
        print(f"             {name:<30s} single={single_frame_dims[name]:>3d}  history={single_frame_dims[name] * history_length:>3d}")

    # ---- Load MuJoCo model -----------------------------------------------
    m = mujoco.MjModel.from_xml_path(xml_path)
    d = mujoco.MjData(m)
    m.opt.timestep = sim_dt

    mj_joint_names = list_mujoco_joint_names(m)
    assert len(mj_joint_names) == n_dof, (
        f"MuJoCo has {len(mj_joint_names)} hinge/slide joints, YAML says {n_dof}."
    )

    isaac_to_mj, mj_to_isaac, action_to_isaac = build_joint_maps(
        joint_names_isaac, joint_names_action, mj_joint_names
    )
    print("[deploy] joint maps built — Isaac/MuJoCo joint sets match.")

    kp_mj = kp_isaac[mj_to_isaac]
    kd_mj = kd_isaac[mj_to_isaac]
    q_default_mj = q_default_isaac[mj_to_isaac]

    # Per-joint torque limits from actuator ctrlrange (NaN guard).
    tau_limit_mj = np.zeros(n_dof, dtype=np.float32)
    for j_mj, name in enumerate(mj_joint_names):
        for a in range(m.nu):
            if m.actuator_trnid[a, 0] == mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, name):
                lo, hi = m.actuator_ctrlrange[a]
                tau_limit_mj[j_mj] = max(abs(lo), abs(hi))
                break
        else:
            tau_limit_mj[j_mj] = 1e6
    print(f"[deploy] torque clamps     : min={tau_limit_mj.min():.1f}  max={tau_limit_mj.max():.1f} Nm")

    # ---- Load policy -----------------------------------------------------
    policy = torch.jit.load(policy_path, map_location="cpu").eval()
    n_params = sum(p.numel() for p in policy.parameters())
    print(f"[deploy] policy loaded ({n_params:,} params)")

    # ---- Initial state ---------------------------------------------------
    set_default_pose(m, d, q_default_isaac, isaac_to_mj, args.base_height)

    lowest_z = float("inf")
    for g in range(m.ngeom):
        if m.geom_bodyid[g] == 0:
            continue
        lowest_z = min(lowest_z, float(d.geom_xpos[g, 2]))
    print(f"[deploy] init lowest geom z = {lowest_z:.4f}  (negative ⇒ ground penetration)")

    # ---- Build obs builder ----------------------------------------------
    obs_builder = V3ObsBuilder(
        m=m, d=d,
        isaac_to_mj=isaac_to_mj,
        action_dim=action_dim,
        n_dof_total=n_dof,
        history_length=history_length,
        obs_term_order=obs_term_order,
        single_frame_dims=single_frame_dims,
    )
    obs_builder.q_default_isaac = q_default_isaac.copy()
    obs_builder.vel_cmd = np.array([args.cmd_lin_x, args.cmd_lin_y, args.cmd_ang_z], dtype=np.float32)
    obs_builder.left_ee_cmd = np.array(args.left_ee, dtype=np.float32)
    obs_builder.right_ee_cmd = np.array(args.right_ee, dtype=np.float32)
    obs_builder.body_height_cmd = np.array([args.cmd_body_height], dtype=np.float32)
    obs_builder.waist_alpha_cmd = np.array([args.cmd_waist_alpha], dtype=np.float32)

    print(f"[deploy] cmd_velocity      : {obs_builder.vel_cmd.tolist()}")
    print(f"[deploy] left_ee_cmd       : {obs_builder.left_ee_cmd.tolist()}")
    print(f"[deploy] right_ee_cmd      : {obs_builder.right_ee_cmd.tolist()}")
    print(f"[deploy] cmd_body_height   : {args.cmd_body_height}")
    print(f"[deploy] cmd_waist_alpha   : {args.cmd_waist_alpha}")
    print(f"[deploy] torso_link body_id: {obs_builder.torso_id}")
    print(f"[deploy] starting viewer …")

    # Verify obs dimension on first call.
    first_obs = obs_builder.step()
    if first_obs.shape[0] != total_obs_dim_yaml:
        raise RuntimeError(
            f"First obs dim {first_obs.shape[0]} != expected {total_obs_dim_yaml}. "
            f"Check obs term order or single-frame dims."
        )
    print(f"[deploy] first obs dim     : {first_obs.shape[0]} ✓")
    # Reset history so the first true step doesn't reuse the warmup frame.
    obs_builder.reset_history()

    # ---- Control loop ---------------------------------------------------
    target_dof_pos_mj = q_default_mj.copy()
    counter = 0

    with mujoco.viewer.launch_passive(m, d) as viewer:
        start = time.time()
        while viewer.is_running() and time.time() - start < args.duration:
            step_start = time.time()

            # PD control every physics step
            q_mj = d.qpos[7:]
            dq_mj = d.qvel[6:]
            tau = kp_mj * (target_dof_pos_mj - q_mj) - kd_mj * dq_mj
            tau = np.clip(tau, -tau_limit_mj, tau_limit_mj)
            d.qfrc_applied[6:] = tau

            mujoco.mj_step(m, d)
            counter += 1

            # NaN guard
            if not np.all(np.isfinite(d.qpos)):
                print(f"[deploy] !! qpos went NaN at step {counter} — stopping.")
                print(f"[deploy]    base z just before NaN: {d.qpos[2]:.4f}")
                print(f"[deploy]    last tau abs max: {np.abs(tau).max():.2f}")
                break

            # Policy every `decimation` steps
            if counter % decimation == 0:
                obs = obs_builder.step()
                with torch.no_grad():
                    obs_t = torch.from_numpy(obs).unsqueeze(0)
                    action_t = policy(obs_t)
                action = action_t.detach().numpy().squeeze(0).astype(np.float32)
                obs_builder.last_action = action.copy()

                # Build PD target in Isaac order: default everywhere, override
                # the action_dim joints with default + scale * action.
                target_dof_pos_isaac = q_default_isaac.copy()
                if use_default_offset:
                    target_dof_pos_isaac[action_to_isaac] = (
                        q_default_isaac[action_to_isaac] + action_scale * action
                    )
                else:
                    target_dof_pos_isaac[action_to_isaac] = action_scale * action
                target_dof_pos_mj = target_dof_pos_isaac[mj_to_isaac]

                # Heartbeat — every ~1s at 50 Hz policy
                policy_steps = counter // decimation
                if policy_steps % 50 == 1:
                    print(
                        f"[deploy] t={d.time:6.2f}s  base_z={d.qpos[2]:.3f}  "
                        f"|action|={np.abs(action).max():.2f}  |tau|={np.abs(tau).max():.1f}"
                    )

            viewer.sync()

            if args.realtime:
                slack = sim_dt - (time.time() - step_start)
                if slack > 0:
                    time.sleep(slack)

    print(f"[deploy] simulation ended after {time.time() - start:.1f}s, {counter} physics steps")


if __name__ == "__main__":
    sys.exit(main())

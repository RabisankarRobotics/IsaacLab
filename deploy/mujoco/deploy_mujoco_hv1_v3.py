TORSO_BODY_NAME = "torso_link"


def list_mujoco_joint_names(m: mujoco.MjModel) -> List[str]:
    names: List[str] = []
    for i in range(m.njnt):
        if m.jnt_type[i] == mujoco.mjtJoint.mjJNT_FREE:
            continue
        names.append(mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_JOINT, i))
    return names


def build_joint_maps(
    isaac_joint_names: List[str],
    action_joint_names: List[str],
    mj_joint_names: List[str],
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    isaac_set = set(isaac_joint_names)
    mj_set = set(mj_joint_names)
    if isaac_set != mj_set:
        only_isaac = isaac_set - mj_set
        only_mj = mj_set - isaac_set
        raise RuntimeError(
            f"Joint name mismatch.\n"
            f"  In Isaac, not in MuJoCo: {sorted(only_isaac)}\n"
            f"  In MuJoCo, not in Isaac: {sorted(only_mj)}"
        )
    if set(action_joint_names) - isaac_set:
        raise RuntimeError(f"Action joints not in Isaac joint list: {set(action_joint_names) - isaac_set}")
    isaac_to_mj = np.array([mj_joint_names.index(n) for n in isaac_joint_names], dtype=np.int64)
    mj_to_isaac = np.array([isaac_joint_names.index(n) for n in mj_joint_names], dtype=np.int64)
    action_to_isaac = np.array([isaac_joint_names.index(n) for n in action_joint_names], dtype=np.int64)
    return isaac_to_mj, mj_to_isaac, action_to_isaac


def get_body_ang_vel_local(m: mujoco.MjModel, d: mujoco.MjData, body_id: int) -> np.ndarray:
    """Angular velocity of a body, expressed in that body's local link frame.

    Uses MuJoCo's mj_objectVelocity with flg_local=1, which is the equivalent
    of Isaac's `quat_apply_inverse(body_quat, body_link_ang_vel_w)` for the
    same body.
    """
    res = np.zeros(6, dtype=np.float64)
    mujoco.mj_objectVelocity(m, d, mujoco.mjtObj.mjOBJ_XBODY, body_id, res, 1)
    return res[:3].astype(np.float32)  # res[:3] = ang_vel, res[3:] = lin_vel


# ---------------------------------------------------------------------------
# Initial state
# ---------------------------------------------------------------------------

def set_default_pose(
    m: mujoco.MjModel,
    d: mujoco.MjData,
    q_default_isaac: np.ndarray,
    isaac_to_mj: np.ndarray,
    base_height: float | None,
) -> None:
    mujoco.mj_resetData(m, d)
    if m.nkey > 0:
        mujoco.mj_resetDataKeyframe(m, d, 0)
        if base_height is not None:
            d.qpos[2] = base_height
        print(f"[deploy] init pose: keyframe 0 loaded, base z = {d.qpos[2]:.3f}")
    else:
        d.qpos[:] = 0.0
        d.qvel[:] = 0.0
        d.qpos[2] = base_height if base_height is not None else 0.95
        d.qpos[3] = 1.0
        q_default_mj = q_default_isaac[np.argsort(isaac_to_mj)]
        d.qpos[7 : 7 + len(q_default_mj)] = q_default_mj
        print(f"[deploy] init pose: built from YAML, base z = {d.qpos[2]:.3f}")
    mujoco.mj_forward(m, d)


# ---------------------------------------------------------------------------
# Observation builder — one function per V3 obs term, exact name match
# ---------------------------------------------------------------------------
#
# Single-frame obs layout (121-d), in PolicyCfg declaration order:
#
#   [0:3]      base_ang_vel             pelvis IMU, body frame
#   [3:6]      projected_gravity        gravity in pelvis frame
#   [6:9]      projected_gravity_torso  gravity in torso_link frame
#   [9:12]     torso_ang_vel            torso_link ang vel in torso_link frame
#   [12:15]    velocity_commands        [vx, vy, wz]
#   [15:46]    joint_pos                (q - q_default), Isaac order, 31 dims
#   [46:77]    joint_vel                dq, Isaac order, 31 dims
#   [77:105]   actions                  previous action, 28 dims
#   [105:112]  left_ee_pose_command     [px py pz qw qx qy qz] in pelvis frame
#   [112:119]  right_ee_pose_command    same, right
#   [119:120]  body_height_command      scalar (m)
#   [120:121]  waist_alpha_command      scalar (alpha_t)
#
# Total: 3+3+3+3+3+31+31+28+7+7+1+1 = 121
# With history_length=5: 605-d actor input (per-term flatten, then concat).


# Terms with no per-step computation (constant commands set once per CLI run).
# Stored on the runtime state object via the closure below.

class V3ObsBuilder:
    """Builds V3 single-frame observation and maintains per-term history."""

    def __init__(
        self,
        m: mujoco.MjModel,
        d: mujoco.MjData,
        isaac_to_mj: np.ndarray,
        action_dim: int,
        n_dof_total: int,
        history_length: int,
        obs_term_order: List[str],
        single_frame_dims: Dict[str, int],
    ):
        self.m = m
        self.d = d
        self.isaac_to_mj = isaac_to_mj
        self.history_length = history_length
        self.obs_term_order = obs_term_order
        self.single_frame_dims = single_frame_dims

        # Torso link body id (cached)
        self.torso_id = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, TORSO_BODY_NAME)
        if self.torso_id < 0:
            raise RuntimeError(f"Body '{TORSO_BODY_NAME}' not found in MuJoCo model.")

        # Runtime state set by main() before each policy step.
        self.q_default_isaac: np.ndarray = np.zeros(n_dof_total, dtype=np.float32)
        self.last_action: np.ndarray = np.zeros(action_dim, dtype=np.float32)
        self.vel_cmd: np.ndarray = np.zeros(3, dtype=np.float32)
        self.left_ee_cmd: np.ndarray = np.zeros(7, dtype=np.float32)
        self.right_ee_cmd: np.ndarray = np.zeros(7, dtype=np.float32)
        self.body_height_cmd: np.ndarray = np.zeros(1, dtype=np.float32)
        self.waist_alpha_cmd: np.ndarray = np.zeros(1, dtype=np.float32)

        # Per-term history buffers — deque ordered oldest-first to match
        # IsaacLab CircularBuffer.buffer property (most recent at the END).
        self.history: Dict[str, deque] = {
            name: deque(maxlen=history_length) for name in obs_term_order
        }

        # Dispatch table for term name → compute function
        self._term_fns: Dict[str, Callable[[], np.ndarray]] = {
            "base_ang_vel": self._base_ang_vel,
            "projected_gravity": self._projected_gravity,
            "projected_gravity_torso": self._projected_gravity_torso,
            "torso_ang_vel": self._torso_ang_vel,
            "velocity_commands": self._velocity_commands,
            "joint_pos": self._joint_pos,
            "joint_vel": self._joint_vel,
            "actions": self._actions,
            "left_ee_pose_command": self._left_ee_pose_command,
            "right_ee_pose_command": self._right_ee_pose_command,
            "body_height_command": self._body_height_command,
            "waist_alpha_command": self._waist_alpha_command,
        }
        missing = [t for t in obs_term_order if t not in self._term_fns]
        if missing:
            raise RuntimeError(f"No compute function for obs terms: {missing}")

    # -- Term computers ----------------------------------------------------

    def _base_ang_vel(self) -> np.ndarray:
        # qvel[3:6] for free joint = body-frame angular velocity in MuJoCo.
        return self.d.qvel[3:6].astype(np.float32).copy()

    def _projected_gravity(self) -> np.ndarray:
        base_quat = self.d.qpos[3:7].astype(np.float32)
        return projected_gravity_in_frame(base_quat)

    def _projected_gravity_torso(self) -> np.ndarray:
        # d.xquat[body_id] = body-to-world quaternion (w, x, y, z)
        torso_quat = self.d.xquat[self.torso_id].astype(np.float32)
        return projected_gravity_in_frame(torso_quat)

    def _torso_ang_vel(self) -> np.ndarray:
        return get_body_ang_vel_local(self.m, self.d, self.torso_id)

    def _velocity_commands(self) -> np.ndarray:
        return self.vel_cmd

    def _joint_pos(self) -> np.ndarray:
        # joint_pos_rel = q - q_default, Isaac joint order
        q_mj = self.d.qpos[7:].astype(np.float32)
        q_isaac = q_mj[self.isaac_to_mj]
        return q_isaac - self.q_default_isaac

    def _joint_vel(self) -> np.ndarray:
        dq_mj = self.d.qvel[6:].astype(np.float32)
        return dq_mj[self.isaac_to_mj]

    def _actions(self) -> np.ndarray:
        return self.last_action

    def _left_ee_pose_command(self) -> np.ndarray:
        return self.left_ee_cmd

    def _right_ee_pose_command(self) -> np.ndarray:
        return self.right_ee_cmd

    def _body_height_command(self) -> np.ndarray:
        return self.body_height_cmd

    def _waist_alpha_command(self) -> np.ndarray:
        return self.waist_alpha_cmd

    # -- History assembly --------------------------------------------------

    def reset_history(self) -> None:
        """Clear all per-term history buffers."""
        for q in self.history.values():
            q.clear()

    def step(self) -> np.ndarray:
        """Compute current frame for each term, push to history, return flat obs."""
        per_term_flat: List[np.ndarray] = []
        for term_name in self.obs_term_order:
            current = self._term_fns[term_name]().astype(np.float32)
            expected = self.single_frame_dims[term_name]
            if current.shape != (expected,):
                raise RuntimeError(
                    f"Term '{term_name}' produced shape {current.shape}, expected ({expected},)"
                )
            buf = self.history[term_name]
            buf.append(current)
            # Pad with the first real frame at startup so the buffer is always
            # full — matches IsaacLab CircularBuffer behaviour (first push fills
            # all empty slots, see circular_buffer.py:137-141).
            while len(buf) < self.history_length:
                buf.append(current)
            # Flatten oldest → newest (deque is already in that order).
            per_term_flat.append(np.concatenate(list(buf), axis=0))
        return np.concatenate(per_term_flat, axis=0).astype(np.float32)


